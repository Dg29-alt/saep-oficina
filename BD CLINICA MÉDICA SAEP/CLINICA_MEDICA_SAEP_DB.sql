CREATE DATABASE IF NOT EXISTS CLINICA_MEDICA_SAEP_DB;
USE CLINICA_MEDICA_SAEP_DB;

CREATE TABLE IF NOT EXISTS USUARIO(
	USU_ID INT AUTO_INCREMENT PRIMARY KEY,
    USU_NOME VARCHAR(100) NOT NULL,
    USU_EMAIL VARCHAR(100) NOT NULL,
    USU_SENHA VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS RESPONSAVEL(
	RES_ID INT AUTO_INCREMENT PRIMARY KEY, 
    RES_NOME VARCHAR(100) NOT NULL,
    RES_DATA_NASCIMENTO DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS PACIENTE(
	PAC_ID INT AUTO_INCREMENT PRIMARY KEY,
    PAC_NOME VARCHAR(100) NOT NULL,
    PAC_DATA_NASCIMENTO DATE NOT NULL,
    FK_RES_ID INT NOT NULL,
    FOREIGN KEY (FK_RES_ID) REFERENCES RESPONSAVEL(RES_ID)
);

CREATE TABLE IF NOT EXISTS AGENDAMENTO(
	AGE_ID INT AUTO_INCREMENT PRIMARY KEY,
    AGE_DATA_HORA DATETIME NOT NULL,
    AGE_MOTIVO VARCHAR(100) NOT NULL,
    AGE_STATUS VARCHAR(30) NOT NULL,
    FK_PAC_ID INT NOT NULL,
    FK_RES_ID INT NOT NULL,
    FOREIGN KEY (FK_PAC_ID) REFERENCES PACIENTE(PAC_ID),
    FOREIGN KEY (FK_RES_ID) REFERENCES RESPONSAVEL(RES_ID)
);

